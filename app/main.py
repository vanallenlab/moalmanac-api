import json
import os

import fastapi

from app import database, dereferenced, schemas
from app.routers.main import router as main_router


class PrettyJSONResponse(fastapi.responses.JSONResponse):
    def render(self, content: object) -> bytes:
        """
        Serializes the given content to indented JSON bytes for the HTTP response.

        Args:
            content (object): The content to serialize as JSON.

        Returns:
            bytes: The UTF-8 encoded, indented JSON representation of content.
        """
        return json.dumps(content, indent=2, ensure_ascii=False).encode("utf-8")


def strip_nullable_query_parameters(schema: dict) -> dict:
    """
    Removes the null branch from each query parameter's schema, in place.

    Optional query parameters are typed `X | None` so their None default type
    checks, which Pydantic renders as `anyOf: [X, {"type": "null"}]`. A query
    parameter is omitted rather than sent as null, so the null branch only clutters
    the documentation. Response schemas are left alone, where null is a real value.

    Args:
        schema (dict): The OpenAPI schema generated by FastAPI.

    Returns:
        dict: The same schema, with `anyOf: [X, null]` replaced by `X` for every
            query parameter.
    """
    for path_item in schema.get("paths", {}).values():
        for operation in path_item.values():
            for parameter in operation.get("parameters", []):
                if parameter.get("in") != "query":
                    continue
                parameter_schema = parameter.get("schema", {})
                branches = parameter_schema.get("anyOf", [])
                non_null = [branch for branch in branches if branch != {"type": "null"}]
                if len(branches) == 2 and len(non_null) == 1:
                    del parameter_schema["anyOf"]
                    parameter_schema.update(non_null[0])
    return schema


def create_app(config_path: str = "config.ini") -> fastapi.FastAPI:
    """
    Creates and configures the FastAPI application instance.

    Initializes the database connection from the provided config file, attaches the
    session factory and the dereferenced record cache to application state, and
    registers the main router.

    The database is not created here. It must already exist and match the current
    schema; run `python -m app.populate_database` first. This keeps a stale or
    partial database file from being silently patched with new tables at startup.

    Args:
        config_path (str): The path to the application configuration file (default: "config.ini").

    Returns:
        fastapi.FastAPI: The configured FastAPI application instance.

    Raises:
        FileNotFoundError: If the configured database file does not exist.
    """
    app = fastapi.FastAPI(
        contact={
            "name": "MOAlmanac API GitHub",
            "url": "https://github.com/vanallenlab/moalmanac-api",
        },
        default_response_class=PrettyJSONResponse,
        description=(
            "The Molecular Oncology Almanac (MOAlmanac) is a paired knowledgebase and clinical interpretation "
            "algorithm for precision cancer medicine. Visit [our website](https://moalmanac.org) for more "
            "information.\n\n"
            "**Filtering**\n\n"
            "- Different filters combine with AND: `?gene=BRAF&disease=Melanoma` returns records "
            "matching all of them.\n"
            "- Repeating a filter combines its values with OR: `?gene=BRAF&gene=KRAS` returns records "
            "matching any of them.\n"
            "- Exception: on `/search`, the `document`, `indication`, and `agent_id` filters narrow "
            "each proposition's statement aggregates rather than which propositions are returned. "
            "See the `/search` endpoint for details."
        ),
        docs_url="/",
        license_info={
            "name": "License: GNU GPL, Version 2",
            "url": "https://github.com/vanallenlab/moalmanac-api/blob/main/LICENSE",
        },
        openapi_tags=[
            {
                "name": "Service Info",
                "description": "Get metadata about the API service.",
            },
            {
                "name": "Search",
                "description": "Search across database records. Primarily uses /propositions endpoint with additional aggregated information.",
            },
            {
                "name": "Entities",
                "description": "Access to the database content.",
            },
        ],
        title="Molecular Oncology Almanac API",
        redoc_url=None,
        version="draft",
    )

    config = database.read_config_ini(path=config_path)
    database_path = config["database"]["path"]
    if not os.path.exists(database_path):
        raise FileNotFoundError(
            f"{database_path} does not exist. Run "
            "`python -m app.populate_database -i moalmanac-db/referenced -c "
            f"{config_path}` to create it.",
        )

    _, session_factory = database.init_db(config_path=config_path)
    with session_factory() as session:
        cache = dereferenced.build_cache(session=session)

    app.state.session_factory = session_factory
    app.state.dereferenced = cache

    app.include_router(main_router)

    def openapi() -> dict:
        """
        Generates the OpenAPI schema once, without null branches on query parameters
        and with moalmanac-db's record schemas added as components.

        Returns:
            dict: The cached OpenAPI schema.
        """
        if app.openapi_schema is None:
            schema = fastapi.FastAPI.openapi(app)
            strip_nullable_query_parameters(schema=schema)
            schema.setdefault("components", {}).setdefault("schemas", {}).update(
                schemas.build_components(),
            )
        return app.openapi_schema

    app.openapi = openapi
    return app


app = create_app()
